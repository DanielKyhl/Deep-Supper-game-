const Font = {
  _cache: {},

  // { rows: [bitmask...], w: columns } for a character
  glyph(ch) {
    let gl = this._cache[ch];
    if (gl) return gl;
    let spec = GLYPHS[ch];
    if (spec === undefined) spec = GLYPHS[ch.toUpperCase()];
    if (spec === undefined) spec = GLYPHS['?'];
    const rows = spec.split('/');
    const w = rows[0].length;
    const bits = rows.map(r => {
      let n = 0;
      for (let i = 0; i < w; i++) if (r[i] === '1') n |= (1 << (w - 1 - i));
      return n;
    });
    gl = { bits, w };
    this._cache[ch] = gl;
    return gl;
  },

  // advance width of a string, in 960-space pixels
  width(str, px) {
    let w = 0;
    for (const ch of String(str)) {
      w += (ch === ' ' ? 3 : this.glyph(ch).w + 1) * px;
    }
    return w - px;   // no trailing gap
  },

  height(px) { return FONT_H * px; },

  /* Draw a string. x,y and px are in 960-space; px must be a multiple of
     PIX so every font pixel lands exactly on one buffer pixel. y is the
     TOP of the glyph box. */
  /* Add a string's pixels to the current path as rectangles. Horizontally
     adjacent pixels are merged into one rect, and the caller fills the
     whole string (or several offset copies of it, for an outline) in a
     single fill — one path beats several hundred fillRect calls. */
  path(g, str, x, y, px) {
    let cx = x;
    for (const ch of str) {
      if (ch === ' ') { cx += 3 * px; continue; }
      const gl = this.glyph(ch);
      for (let r = 0; r < FONT_H; r++) {
        const bits = gl.bits[r];
        if (!bits) continue;
        let run = 0;
        for (let c = 0; c <= gl.w; c++) {
          const on = c < gl.w && (bits & (1 << (gl.w - 1 - c)));
          if (on) { run++; continue; }
          if (run) { g.rect(cx + (c - run) * px, y + r * px, run * px, px); run = 0; }
        }
      }
      cx += (gl.w + 1) * px;
    }
    return cx - px;
  },

  draw(g, str, x, y, px, color) {
    g.beginPath();
    const end = this.path(g, String(str), x, y, px);
    g.fillStyle = color;
    g.fill();
    return end;
  }
};
